package main // Объявляем пакет main, потому что именно с него начинается выполнение программы

import (
	"fmt"      // Подключаем fmt для чтения данных из терминала и форматированного вывода
	"strconv"  // Подключаем strconv, чтобы преобразовать строку со скоростью в число
)

// TODO: 1. Определите интерфейс Vehicle с методом GetInfo() string
type Vehicle interface { // Создаём интерфейс Vehicle — он описывает, какой метод обязан иметь подходящий тип
	GetInfo() string // Требуем от типа метод GetInfo, который ничего не принимает и возвращает строку
}

// TODO: 2. Определите структуру Car с полями Brand (string) и Speed (int)
type Car struct { // Создаём структуру Car, которая будет хранить данные автомобиля
	Brand string // Поле Brand хранит марку автомобиля в виде строки
	Speed int    // Поле Speed хранит скорость автомобиля в виде целого числа
}

// TODO: 3. Реализуйте метод GetInfo() для Car
func (c Car) GetInfo() string { // Создаём метод GetInfo для Car; c — копия конкретного автомобиля, метод возвращает string
	return fmt.Sprintf("Brand: %s, Speed: %d km/h", c.Brand, c.Speed) // Формируем строку из полей c.Brand и c.Speed и возвращаем её
}

func main() { // Точка входа программы — выполнение начинается отсюда
	// Чтение входных данных
	var brand string // Создаём переменную для хранения марки автомобиля, которую введёт пользователь
	var speedStr string // Создаём переменную для хранения скорости в виде строки, потому что ввод из терминала читается как текст
	fmt.Scanln(&brand) // Читаем марку из терминала и записываем её в переменную brand
	fmt.Scanln(&speedStr) // Читаем скорость из терминала и записываем её в speedStr как строку

	// Преобразование строки скорости в целое число
	speed, _ := strconv.Atoi(speedStr) // Преобразуем speedStr из string в int; _ означает, что ошибку преобразования мы здесь игнорируем

	// TODO: 4. Создайте экземпляр Car, используя brand и speed, затем вызовите GetInfo()
	car := Car{ // Создаём конкретный экземпляр структуры Car и сохраняем его в переменную car
		Brand: brand, // Передаём введённую марку brand в поле Brand созданного автомобиля
		Speed: speed, // Передаём преобразованную скорость speed в поле Speed созданного автомобиля
	}

	// Вывод результата
	result := car.GetInfo() // Вызываем метод GetInfo у car и сохраняем возвращённую им строку в переменную result
	fmt.Println(result) // Выводим готовую строку result в терминал
}

