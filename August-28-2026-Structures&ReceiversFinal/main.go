package main // Объявляем пакет main, потому что с него начинается выполнение программы

import ( // Подключаем пакеты, которые понадобятся ниже
	"fmt"      // fmt нужен для чтения данных и вывода результата в терминал
	"strconv"  // strconv нужен для преобразования строк в числа
)

type Rectangle struct { // Создаём структуру Rectangle, которая хранит данные прямоугольника
    Width float64 // Храним ширину прямоугольника как число с плавающей точкой
    Height float64 // Храним высоту прямоугольника как число с плавающей точкой
}

func (a Rectangle) area() float64 { // Value receiver: метод получает копию Rectangle и возвращает площадь типа float64
    return a.Width * a.Height // Умножаем ширину на высоту и возвращаем полученную площадь
}

func (a *Rectangle) scale(tron float64) { // Pointer receiver: метод получает указатель, чтобы изменить исходный Rectangle
    a.Width = a.Width * tron // Умножаем ширину на коэффициент масштабирования и сохраняем новый результат
    a.Height = a.Height * tron // Умножаем высоту на коэффициент масштабирования и сохраняем новый результат
}

func main() { // Точка входа программы: выполнение начинается отсюда
	var widthStr string // Создаём строковую переменную для чтения ширины из терминала
	var heightStr string // Создаём строковую переменную для чтения высоты из терминала
	var scaleStr string // Создаём строковую переменную для чтения коэффициента масштабирования
	fmt.Scanln(&widthStr) // Считываем ширину из терминала и записываем её как строку
	fmt.Scanln(&heightStr) // Считываем высоту из терминала и записываем её как строку
	fmt.Scanln(&scaleStr) // Считываем коэффициент масштабирования из терминала и записываем его как строку
	
	width, _ := strconv.ParseFloat(widthStr, 64) // Преобразуем строковую ширину в число float64
	height, _ := strconv.ParseFloat(heightStr, 64) // Преобразуем строковую высоту в число float64
	scaleFactor, _ := strconv.ParseFloat(scaleStr, 64) // Преобразуем строковый коэффициент в число float64
	
	rectangle := Rectangle{ // Создаём экземпляр Rectangle и сразу заполняем его данными
        Width: width, // Передаём полученную ширину в поле Width
        Height: height, // Передаём полученную высоту в поле Height
    }

    initialArea := rectangle.area() // Вызываем area до масштабирования и сохраняем исходную площадь
	fmt.Printf("Initial area: %.0f\n", initialArea) // Выводим исходную площадь без десятичной части
	
    rectangle.scale(scaleFactor) // Передаём коэффициент в scale, который изменяет Width и Height исходного rectangle
    scaledArea := rectangle.area() // После масштабирования заново вычисляем площадь изменённого прямоугольника
    fmt.Printf("Scaled area: %.0f\n", scaledArea) // Выводим площадь после масштабирования без десятичной части
}
